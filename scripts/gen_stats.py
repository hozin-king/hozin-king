#!/usr/bin/env python3
"""Generate self-hosted GitHub stats cards (stats.svg + top-langs.svg).

Replaces the github-readme-stats.vercel.app embeds (rate-limited / down)
with SVGs generated by GitHub Actions and served from this repo itself,
so GitHub renders them from its own domain.

Data: GitHub REST API with GH_TOKEN (Actions: secrets.GITHUB_TOKEN).
Set GEN_STATS_MOCK=1 to render with fake numbers (local preview only).
Stdlib only. Run from repo root: python3 scripts/gen_stats.py
"""
import json
import os
import sys
import urllib.request
import urllib.error
from xml.sax.saxutils import escape

USER = "hozin-king"
API = "https://api.github.com"

# GitHub linguist colors for the languages this user actually uses.
LANG_COLORS = {
    "Kotlin": "#A97BFF", "Java": "#b07219", "C++": "#f34b7d",
    "Python": "#3572A5", "JavaScript": "#f1e05a", "TypeScript": "#3178c6",
    "C": "#555555", "C#": "#178600", "HTML": "#e34c26", "CSS": "#563d7c",
    "Go": "#00ADD8", "Rust": "#dea584", "Shell": "#89e051",
    "Dart": "#00B4AB", "PHP": "#4F5D95", "Ruby": "#701516",
    "Swift": "#F05138", "Vue": "#41b883", "Dockerfile": "#384d54",
    "CMake": "#DA3434", "GLSL": "#5686a5", "PowerShell": "#012456",
    "Lua": "#000080", "Assembly": "#6E4C13", "Jupyter Notebook": "#DA5B0B",
    "Kotlin Script": "#A97BFF", "Smali": "#D6D6D6",
}

BG = "#0D1117"
BORDER = "#30363d"
TITLE = "#00F0FF"
TEXT = "#ffffff"
MUTED = "#8b949e"
ACCENT = "#FF00E5"


def api(path):
    token = os.environ.get("GH_TOKEN", "")
    req = urllib.request.Request(
        API + path,
        headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": "hozin-king-profile-stats",
            **({"Authorization": f"Bearer {token}"} if token else {}),
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        print(f"API {path} -> HTTP {e.code}", file=sys.stderr)
        raise


def fetch_data():
    if os.environ.get("GEN_STATS_MOCK") == "1":
        return {
            "stars": 4, "commits": 418, "prs": 2, "issues": 0,
            "repos": 55, "followers": 1,
            "langs": [("Kotlin", 42.5), ("Java", 28.3), ("C++", 12.1),
                      ("Python", 9.4), ("JavaScript", 4.2), ("HTML", 3.5)],
        }
    user = api(f"/users/{USER}")
    repos = api(f"/users/{USER}/repos?per_page=100&sort=updated")
    owned = [r for r in repos
             if not r.get("fork") and not r.get("archived")
             and r["name"] != USER]
    stars = sum(r.get("stargazers_count", 0) for r in owned)
    commits = api(f"/search/commits?q=author:{USER}&per_page=1")["total_count"]
    prs = api(f"/search/issues?q=type:pr+author:{USER}&per_page=1")["total_count"]
    issues = api(f"/search/issues?q=type:issue+author:{USER}&per_page=1")["total_count"]
    lang_bytes = {}
    for r in owned:
        try:
            for lang, n in api(f"/repos/{r['full_name']}/languages").items():
                lang_bytes[lang] = lang_bytes.get(lang, 0) + n
        except Exception as e:
            print(f"languages {r['full_name']}: {e}", file=sys.stderr)
    total = sum(lang_bytes.values()) or 1
    langs = sorted(((l, b / total * 100) for l, b in lang_bytes.items()),
                   key=lambda x: -x[1])[:6]
    return {
        "stars": stars, "commits": commits, "prs": prs, "issues": issues,
        "repos": len(owned), "followers": user.get("followers", 0),
        "langs": langs,
    }


def stats_svg(d):
    rows = [
        ("Total Stars", d["stars"]),
        ("Total Commits", d["commits"]),
        ("Total PRs", d["prs"]),
        ("Total Issues", d["issues"]),
        ("Public Repos", d["repos"]),
    ]
    y = 52
    body = []
    for label, val in rows:
        body.append(
            f'<text x="24" y="{y}" fill="{TEXT}" font-size="13" '
            f'font-family="Segoe UI, Ubuntu, Sans-Serif">{escape(label)}</text>'
            f'<text x="376" y="{y}" fill="{TITLE}" font-size="13" font-weight="bold" '
            f'text-anchor="end" font-family="Segoe UI, Ubuntu, Sans-Serif">{val}</text>'
        )
        y += 30
    height = y + 8
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="400" height="{height}" viewBox="0 0 400 {height}">
<rect x="0.5" y="0.5" width="399" height="{height - 1}" rx="8" fill="{BG}" stroke="{BORDER}"/>
<text x="24" y="30" fill="{TITLE}" font-size="16" font-weight="bold" font-family="Segoe UI, Ubuntu, Sans-Serif">Hozin King&apos;s GitHub Stats</text>
<circle cx="376" cy="24" r="5" fill="{ACCENT}"/>
{''.join(body)}
</svg>
'''


def top_langs_svg(d):
    langs = d["langs"]
    top = langs[0][1] if langs else 1
    y = 56
    body = []
    for lang, pct in langs:
        color = LANG_COLORS.get(lang, "#8b949e")
        w = max(8, int(300 * pct / top))
        body.append(
            f'<circle cx="30" cy="{y - 4}" r="5" fill="{color}"/>'
            f'<text x="42" y="{y}" fill="{TEXT}" font-size="12" '
            f'font-family="Segoe UI, Ubuntu, Sans-Serif">{escape(lang)}</text>'
            f'<text x="376" y="{y}" fill="{MUTED}" font-size="12" text-anchor="end" '
            f'font-family="Segoe UI, Ubuntu, Sans-Serif">{pct:.1f}%</text>'
            f'<rect x="24" y="{y + 8}" width="352" height="7" rx="3.5" fill="#21262d"/>'
            f'<rect x="24" y="{y + 8}" width="{int(352 * pct / top)}" height="7" rx="3.5" fill="{color}">'
            f'<animate attributeName="width" from="0" to="{int(352 * pct / top)}" dur="1s" fill="freeze"/></rect>'
        )
        y += 38
    height = y + 6
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="400" height="{height}" viewBox="0 0 400 {height}">
<rect x="0.5" y="0.5" width="399" height="{height - 1}" rx="8" fill="{BG}" stroke="{BORDER}"/>
<text x="24" y="30" fill="{TITLE}" font-size="16" font-weight="bold" font-family="Segoe UI, Ubuntu, Sans-Serif">Most Used Languages</text>
<circle cx="376" cy="24" r="5" fill="{ACCENT}"/>
{''.join(body)}
</svg>
'''


def main():
    d = fetch_data()
    print(json.dumps({k: v for k, v in d.items() if k != "langs"}))
    print("langs:", [(l, round(p, 1)) for l, p in d["langs"]])
    os.makedirs("scripts", exist_ok=True)
    with open("stats.svg", "w", encoding="utf-8") as f:
        f.write(stats_svg(d))
    with open("top-langs.svg", "w", encoding="utf-8") as f:
        f.write(top_langs_svg(d))
    print("wrote stats.svg + top-langs.svg")


if __name__ == "__main__":
    main()
